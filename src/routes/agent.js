router.post(
  "/upload/screenshot",
  authenticateAgent,
  handleUpload(upload.single("screenshot")),
  async (req, res) => {
    try {
      const {
        machine_id,
        latitude,
        longitude,
        city,
        country
      } = req.body;

      const machineId = cleanString(machine_id);

      if (!machineId || !req.file || !req.file.buffer) {
        return res.status(400).json({
          error: "Missing machine_id or file"
        });
      }

      const device = await verifyDeviceToken(
        machineId,
        req.agentToken
      );

      if (!device) {
        console.log("🚨 Screenshot rejected:", machineId);
        return res.status(401).json({
          error: "Invalid device authentication"
        });
      }

      const safeFileName = path.basename(
        req.file.originalname || "screenshot.jpg"
      );

      const cloudResult = await uploadEvidence(
        req.file.buffer,
        safeFileName
      );

      if (!cloudResult || !cloudResult.public_id) {
        throw new Error("Cloudinary did not return an evidence public ID");
      }

      await db.query(
        `
        INSERT INTO device_evidence
        (
          machine_id,
          type,
          file_path,
          latitude,
          longitude,
          city,
          country,
          created_at
        )
        VALUES
        (
          $1,
          'screenshot',
          $2,
          $3,
          $4,
          $5,
          $6,
          NOW()
        )
        `,
        [
          machineId,
          cloudResult.public_id,
          latitude || null,
          longitude || null,
          cleanString(city),
          cleanString(country)
        ]
      );

      await sendEvidenceEmail(
        machineId,
        req.file.buffer,
        safeFileName,
        "Screenshot"
      );

      return res.json({
        success: true
      });
    } catch (err) {
      console.error("🔥 SCREENSHOT ERROR:", err);
      return res.status(500).json({
        error: "Screenshot upload failed"
      });
    }
  }
);

