router.get(

  "/download",

  auth,

  async (req, res) => {

    try {

      const templatePath = path.join(

        __dirname,

        "../agent_template.py"

      );

      let agentCode = fs.readFileSync(

        templatePath,

        "utf8"

      );

      // Generate a cryptographically secure token.

      const agentToken =

        crypto.randomBytes(32).toString("hex");

      agentCode = agentCode.replace(

        "{{USER_ID}}",

        String(req.user.id)

      );

      agentCode = agentCode.replace(

        "{{AGENT_TOKEN}}",

        agentToken

      );

      const tempDir = path.join(

        __dirname,

        "../../temp"

      );

      fs.mkdirSync(tempDir, {

        recursive: true

      });

      const tempFilePath = path.join(

        tempDir,

        `deviceguard-agent-${req.user.id}-${crypto

          .randomBytes(8)

          .toString("hex")}.py`

      );

      fs.writeFileSync(

        tempFilePath,

        agentCode,

        "utf8"

      );

      res.download(

        tempFilePath,

        "deviceguard-agent.py",

        () => {

          try {

            if (fs.existsSync(tempFilePath)) {

              fs.unlinkSync(tempFilePath);

            }

          } catch (err) {

            console.log(

              "⚠️ Temp cleanup failed:",

              err.message

            );

          }

        }

      );

    } catch (err) {

      console.error(

        "🔥 DOWNLOAD AGENT ERROR:",

        err

      );

      res.status(500).json({

        error: "Unable to download agent"

      });

    }

  }

);

