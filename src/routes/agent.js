// AGENT AUTHENTICATION

// ============================================================

function authenticateAgent(req, res, next) {

  const agentToken = req.headers["x-agent-token"];

  // IMPORTANT:

  // Log the exact endpoint when a token is missing.

  // This helps us identify any client still making

  // an unauthenticated request.

  if (!agentToken) {

    console.log(

      "🚨 Agent request rejected: missing token",

      "| METHOD:",

      req.method,

      "| URL:",

      req.originalUrl,

      "| USER-AGENT:",

      req.headers["user-agent"] || "unknown"

    );

    return res.status(401).json({

      error: "Agent authentication required"

    });

  }

  if (!isValidAgentToken(agentToken)) {

    console.log(

      "🚨 Agent request rejected: invalid token format",

      "| METHOD:",

      req.method,

      "| URL:",

      req.originalUrl

    );

    return res.status(401).json({

      error: "Invalid agent authentication"

    });

  }

  req.agentToken = agentToken;

  next();

}

