const MAX_EVIDENCE_SIZE = 10 * 1024 * 1024; // 10 MB

const AGENT_TOKEN_LENGTH = 64;

// ============================================================

// HELPERS

// ============================================================

function cleanString(value) {

  if (value === undefined || value === null) {

    return null;

  }

  const cleaned = String(value).trim();

  return cleaned === "" ? null : cleaned;

}

function escapeHtml(value) {

  return String(value ?? "")

    .replace(/&/g, "&amp;")

    .replace(/</g, "&lt;")

    .replace(/>/g, "&gt;")

    .replace(/"/g, "&quot;")

    .replace(/'/g, "&#039;");

}

// Agent tokens generated by DeviceGuard are:

// 32 random bytes = 64 hexadecimal characters.

function isValidAgentToken(token) {

  return (

    typeof token === "string" &&

    token.length === AGENT_TOKEN_LENGTH &&

    /^[a-f0-9]{64}$/i.test(token)

  );

}

// Constant-time token comparison.

function tokensMatch(tokenA, tokenB) {

  if (

    typeof tokenA !== "string" ||

    typeof tokenB !== "string"

  ) {

    return false;

  }

  const a = Buffer.from(tokenA, "utf8");

  const b = Buffer.from(tokenB, "utf8");

  if (a.length !== b.length) {

    return false;

  }

  return crypto.timingSafeEqual(a, b);

}

