// VERIFY DEVICE TOKEN

// ============================================================

async function verifyDeviceToken(machineId, agentToken) {

  if (!machineId || !agentToken) {

    return null;

  }

  const result = await db.query(

    `

    SELECT

      id,

      user_id,

      machine_id,

      agent_token,

      status

    FROM devices

    WHERE machine_id = $1

    LIMIT 1

    `,

    [machineId]

  );

  if (result.rows.length === 0) {

    return null;

  }

  const device = result.rows[0];

  if (!device.agent_token) {

    return null;

  }

  if (!tokensMatch(device.agent_token, agentToken)) {

    return null;

  }

  return device;

}

