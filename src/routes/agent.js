// EMAIL HELPER

// ============================================================

async function sendEvidenceEmail(
  machine_id,
  fileBuffer,
  fileName,
  type
) {
  try {
    console.log("\n========================================");
    console.log("📧 STARTING EMAIL PROCESS");
    console.log("📎 ATTACHMENT:", fileName);

    if (!Buffer.isBuffer(fileBuffer) || fileBuffer.length === 0) {
      console.log("❌ EVIDENCE BUFFER IS EMPTY OR INVALID");
      return false;
    }

    const result = await db.query(
      `
      SELECT users.email
      FROM devices
      JOIN users
        ON devices.user_id = users.id
      WHERE devices.machine_id = $1
      LIMIT 1
      `,
      [machine_id]
    );

    if (result.rows.length === 0 || !result.rows[0].email) {
      console.log("❌ USER EMAIL NOT FOUND");
      return false;
    }

    const email = result.rows[0].email;
    const safeMachineId = escapeHtml(machine_id);
    const safeType = escapeHtml(type);
    const safeFileName = path.basename(fileName || "evidence.jpg");

    const success = await sendEmail(
      email,
      `📸 DeviceGuard ${type} Evidence`,
      `
        <h2>📸 New ${safeType} Evidence Captured</h2>
        <p>Your stolen device uploaded new evidence.</p>
        <p><b>Machine ID:</b> ${safeMachineId}</p>
        <br>
        <p>— DeviceGuard Security</p>
      `,
      [{ name: safeFileName, buffer: fileBuffer }]
    );

    console.log("📬 EMAIL SUCCESS:", success);
    return success;
  } catch (err) {
    console.log("❌ EMAIL PROCESS FAILED");
    console.log(err);
    return false;
  }
}

